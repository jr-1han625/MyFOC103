/* 按 df/dt 限制频率变化，然后积分 theta/(2*pi)；输出用于本次电压合成。 */
int Foc_OpenLoopStep(float target_hz, float acceleration_hz_s, float period_s,
                     FocOpenLoopState *state, FocOpenLoopOutput *output)
{
    FocOpenLoopState next = *state;
    float delta = acceleration_hz_s * period_s;
    float position, fraction;
    unsigned index, cosine_index;
    if (!isfinite(target_hz) || !isfinite(delta) || !isfinite(period_s) ||
        !(target_hz >= 0.0f) || !(delta > 0.0f) || !(period_s > 0.0f) ||
        !(next.frequency_hz >= 0.0f) || !isfinite(next.frequency_hz) ||
        !(next.phase_turn >= 0.0f && next.phase_turn < 1.0f) ||
        !(target_hz * period_s < 1.0f) || !(next.frequency_hz * period_s < 1.0f)) return 0;
    if (next.frequency_hz < target_hz) {
        next.frequency_hz += delta;
        if (next.frequency_hz > target_hz) next.frequency_hz = target_hz;
    } else {
        next.frequency_hz -= delta;
        if (next.frequency_hz < target_hz) next.frequency_hz = target_hz;
    }
    next.phase_turn += next.frequency_hz * period_s;
    if (next.phase_turn >= 1.0f) next.phase_turn -= 1.0f;
    position = next.phase_turn * 256.0f;
    index = (unsigned)position;
    fraction = position - index;
    cosine_index = (index + 64U) & 255U;
    output->sin_theta = sine[index] + (sine[index + 1U] - sine[index]) * fraction;
    output->cos_theta = sine[cosine_index] + (sine[cosine_index + 1U] - sine[cosine_index]) * fraction;
    *state = next;
    return 1;
}
