/**
  * @brief  This function handles PPP interrupt request.
  * @param  None
  * @retval None
  */
/* 每帧仅调用一次业务计算；结束时检查实时预算并刷新采样看门狗。 */
void ADC1_2_IRQHandler(void)
{
    MotorIoSample sample;
    if (!MotorIo_B.read(&sample)) {
        Motor_Trip(MOTOR_FAULT_SAMPLE);
        return;
    }
    Motor_StartStep(&sample);
    if (motor_start.fault == MOTOR_FAULT_NONE && motor_start.stage != MOTOR_DONE) {
        if (!MotorIo_B.finish()) Motor_Trip(MOTOR_FAULT_TIMING);
    }
}

/* BKIN 已在硬件关断六路，这里锁存业务故障并关闭 DRV_EN。 */
void TIM1_BRK_IRQHandler(void)
{
    if (BSP_MotorBreak()) Motor_Trip(MOTOR_FAULT_DRIVER);
}

/* 比 ADC 更高的抢占优先级，处理采样停止或控制入口卡住。 */
void TIM2_IRQHandler(void)
{
    if (BSP_MotorTimeout()) Motor_Trip(MOTOR_FAULT_TIMING);
}

